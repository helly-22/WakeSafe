"""Rule-based apnea screening tier for WakeSafe (Person A).

Pure functions, no schema imports. Screening aid only.

The STOP-Bang questionnaire tier is the base. Wearable evidence can raise it by at most
one level and can never lower it. Evidence is a set of "signals" that either fire or not:

  * model signal: the runtime model score (resting heart rate and RMSSD) is at or above
    its cutoff. The score is uncalibrated and is never shown as a percentage.
  * trend signals: the recent-night average differs from the person's own earlier nights by
    at least CONFIG["z_threshold"] standard deviations in the worrying direction, for SpO2
    (lower), respiratory rate (higher), disturbances (higher) and sleep efficiency (lower).
    These describe a recent change, not an existing condition.

The tier rises one level only when at least CONFIG["min_signals_to_raise"] signals fire together and
at least one of them is a breathing signal (SpO2 or respiratory rate).
Every entry in `top_factors` is generated by code and carries the number it came from.
All thresholds live in CONFIG, are unreviewed by a clinician, and are printed in the evidence note.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Mapping, Sequence

from .model import StopBangResult, apnea_model_score, score_stopbang

TIERS = ("Low", "Moderate", "High")
SCORING_RULES_VERSION = "apnea-rules-v3"

CONFIG: dict = {
    # z is (recent 7-night mean - earlier-night mean) / earlier-night SD, as in baseline_zscores.
    # With no real change, z has a standard error of about sqrt(1/7 + 1/14) = 0.46 for a 7-night
    # mean against a 14-night baseline, so 1.0 is about 2 standard errors. It was chosen from that
    # arithmetic, not tuned on any data.
    "z_threshold": 1.0,
    "model_cutoff": 0.5,  # fixed in advance, matches backend/app/ml/apnea_resting_hr_rmssd.json
    "min_signals_to_raise": 2,
    # Disturbances and sleep efficiency also change with menopause, illness, stress and travel, so at
    # least one of the signals that raise the tier must be a breathing signal (SpO2 or respiratory rate).
    "breathing_signals": ("spo2_pct", "respiratory_rate_rpm"),
    "min_nights": 7,  # fewer nights than this and wearable data is not used
    "recent_nights": 7,  # window behind the "recent average" wording; matches compute_features
    # The model score is a supporting factor only. In the synthetic smoke test
    # (ml/training/smoke_test_synthetic.py) its signal fired for 68% of healthy synthetic people,
    # above the 50% limit set in advance, so it does not count toward raising the tier.
    "model_counts_toward_raise": False,
}

# key in baseline z-scores -> (label, direction that counts as worrying: -1 lower, +1 higher)
TREND_SIGNALS: dict[str, tuple[str, int]] = {
    "spo2_pct": ("SpO2", -1),
    "respiratory_rate_rpm": ("Respiratory rate", +1),
    "disturbance_count": ("Disturbance count", +1),
    "sleep_efficiency_pct": ("Sleep efficiency", -1),
}

ITEM_LABELS = {
    "snoring": "snoring",
    "tired": "daytime tiredness",
    "observed_apnea": "witnessed breathing pauses",
    "pressure": "high blood pressure",
    "bmi_over_35": "BMI over 35",
    "age_over_50": "age over 50",
    "neck_over_40cm": "neck over 40 cm",
    "male": "male sex",
}
UNKNOWN_LABELS = {
    "snoring": "snoring",
    "tired": "daytime tiredness",
    "observed_apnea": "witnessed breathing pauses",
    "hypertension": "high blood pressure",
    "bmi": "BMI (height or weight missing)",
    "age": "age",
    "neck_cm": "neck size",
    "male": "sex",
}


@dataclass
class ApneaDecision:
    tier: str  # "Low", "Moderate" or "High"
    base_tier: str  # tier from the questionnaire alone
    stop_bang_score: int  # 0 to 8
    raised: bool
    signals_fired: list[str]
    top_factors: list[str]  # code-generated reasons, each with its number
    model_version: str
    evidence_note: str
    model_score: float | None = None  # uncalibrated; never display as a percentage
    raise_reasons: list[str] = field(default_factory=list)


def bmi_from(height_cm: float | None, weight_kg: float | None) -> float | None:
    if not height_cm or not weight_kg or height_cm <= 0 or weight_kg <= 0:
        return None
    return weight_kg / (height_cm / 100.0) ** 2


def raise_one_level(tier: str) -> str:
    return TIERS[min(TIERS.index(tier) + 1, len(TIERS) - 1)]


def _trend_fired(z: float | None, direction: int, threshold: float) -> bool:
    return z is not None and direction * z >= threshold


def stopbang_factors(sb: StopBangResult, bmi: float | None, hypertension_from_conditions: bool = False) -> list[str]:
    yes = []
    for key, label in ITEM_LABELS.items():
        if not sb.items[key]:
            continue
        if key == "bmi_over_35" and bmi is not None:
            label = f"{label} (BMI {bmi:.1f})"
        elif key == "pressure" and hypertension_from_conditions:
            label = f"{label} (counted from the reported conditions)"
        yes.append(label)
    out = [f"STOP-Bang questionnaire score {sb.score} of 8 ({sb.tier}): " + (", ".join(yes) if yes else "no items answered yes")]
    if sb.upgraded:
        extra = [ITEM_LABELS[k] for k in ("bmi_over_35", "neck_over_40cm", "male") if sb.items[k]]
        out.append(
            f"STOP-Bang combination rule raised Moderate to High: {sb.stop_items} of 4 STOP items plus {', '.join(extra)}"
        )
    if sb.missing:
        out.append(
            f"{len(sb.missing)} STOP-Bang answers unknown and counted as no: "
            + ", ".join(UNKNOWN_LABELS[m] for m in sb.missing)
        )
    return out


def decide_apnea_tier(
    stopbang: StopBangResult,
    *,
    bmi: float | None,
    artifact: Mapping | None,
    resting_hr_bpm: float | None,
    hrv_rmssd_ms: float | None,
    z_scores: Mapping[str, float | None],
    nights_available: int,
    nights_with_spo2: int,
    synthetic: bool = False,
    hypertension_from_conditions: bool = False,
    config: Mapping | None = None,
) -> ApneaDecision:
    cfg = CONFIG if config is None else config
    base_tier = stopbang.tier
    factors = stopbang_factors(stopbang, bmi, hypertension_from_conditions)
    fired: list[str] = []
    fired_detail: list[str] = []
    wearable_factors: list[str] = []
    evaluated = 0  # how many wearable signals had data to check

    enough_nights = nights_available >= cfg["min_nights"]
    model_score: float | None = None
    model_version = SCORING_RULES_VERSION
    if artifact is not None:
        model_version = f"{artifact['model_version']}+{SCORING_RULES_VERSION}"

    if not enough_nights:
        wearable_factors.append(
            f"Only {nights_available} nights available and at least {cfg['min_nights']} are needed, "
            "so wearable trends and the heart rate model are not used"
        )
    else:
        # Model signal
        if artifact is not None and resting_hr_bpm is not None and hrv_rmssd_ms is not None:
            model_score = apnea_model_score(artifact, resting_hr_bpm, hrv_rmssd_ms)
            cutoff = cfg["model_cutoff"]
            above = model_score >= cutoff
            counts = cfg["model_counts_toward_raise"]
            if counts:
                evaluated += 1
            wearable_factors.append(
                f"Resting heart rate {resting_hr_bpm:.0f} bpm and HRV (RMSSD) {hrv_rmssd_ms:.0f} ms give a screening score of "
                f"{model_score:.2f} against a cutoff of {cutoff:.2f} ("
                + ("resembles the heart rate pattern of people with frequent breathing pauses in its training recordings" if above else "below the cutoff")
                + "); the score is uncalibrated, is not a percentage, and "
                + ("counts as one signal" if counts else "is shown as supporting information only and does not count toward raising the tier")
            )
            if above and counts:
                fired.append("model")
                fired_detail.append(f"model score {model_score:.2f}")
        else:
            wearable_factors.append(
                f"Resting heart rate and HRV model not used: values missing ({nights_available} nights available)"
            )

        # Trend signals: recent average against the person's own earlier nights
        unavailable = []
        for key, (label, direction) in TREND_SIGNALS.items():
            z = z_scores.get(key)
            if z is None:
                unavailable.append(label)
                continue
            evaluated += 1
            if _trend_fired(z, direction, cfg["z_threshold"]):
                word = "above" if z > 0 else "below"
                wearable_factors.append(
                    f"{label} {cfg['recent_nights']}-night average is {abs(z):.1f} SD {word} your earlier nights"
                )
                fired.append(key)
                fired_detail.append(f"{label} {z:+.1f} SD")
        if unavailable:
            note = f"Earlier-night comparison unavailable for {', '.join(unavailable)} ({nights_available} nights available"
            if "SpO2" in unavailable:
                note += f", SpO2 recorded on {nights_with_spo2} of them"
            wearable_factors.append(note + ")")

    # Tier decision: base tier, raised by at most one level, never lowered
    raise_reasons: list[str] = []
    tier = base_tier
    raised = False
    has_breathing = any(k in cfg["breathing_signals"] for k in fired)
    if len(fired) >= cfg["min_signals_to_raise"] and not has_breathing:
        step = (
            f"{len(fired)} wearable signals fired ({'; '.join(fired_detail)}) but none is a breathing signal "
            f"(SpO2 or respiratory rate), so the tier stays {base_tier}"
        )
    elif len(fired) >= cfg["min_signals_to_raise"]:
        if base_tier == "High":
            step = f"{len(fired)} wearable signals agree ({'; '.join(fired_detail)}), tier already High so unchanged"
        else:
            tier = raise_one_level(base_tier)
            raised = True
            step = f"Raised from {base_tier} to {tier}: {len(fired)} wearable signals agree ({'; '.join(fired_detail)})"
            raise_reasons.append(step)
    elif fired:
        step = (
            f"{len(fired)} wearable signal fired ({'; '.join(fired_detail)}); "
            f"{cfg['min_signals_to_raise']} are needed to raise the tier, so it stays {base_tier}"
        )
    else:
        step = f"0 of {evaluated} wearable signals fired; tier stays {base_tier}"

    top_factors = ([step] if raised else []) + factors + wearable_factors + ([] if raised else [step])

    wearable_used = enough_nights and (model_score is not None or any(z_scores.get(k) is not None for k in TREND_SIGNALS))
    note = (
        "Screening result: the STOP-Bang questionnaire sets the base tier, and wearable trends or a resting heart rate "
        "and HRV model can raise it by at most one level and never lower it. "
        f"Thresholds, all unreviewed by a clinician: recent average at least {cfg['z_threshold']:g} SD away from earlier nights, "
        f"model score at least {cfg['model_cutoff']:g}, {cfg['min_signals_to_raise']} signals to raise one level "
        "including at least one breathing signal (SpO2 or respiratory rate), "
        f"at least {cfg['min_nights']} nights needed"
        + ("" if cfg["model_counts_toward_raise"] else ", model shown as supporting information only")
        + ". The wearable model was trained on clinical ECG data and has not been validated on WHOOP data. "
        "Not a clinical prediction."
    )
    if not wearable_used:
        if not enough_nights:
            why = f"only {nights_available} nights were available and at least {cfg['min_nights']} are needed"
        else:
            why = "the readings it needs were missing"
        note += f" Wearable data was not used because {why}, so the tier reflects the questionnaire only."
    if synthetic:
        note += " Synthetic demonstration data."

    return ApneaDecision(
        tier=tier,
        base_tier=base_tier,
        stop_bang_score=stopbang.score,
        raised=raised,
        signals_fired=fired,
        top_factors=top_factors,
        model_version=model_version,
        evidence_note=note,
        model_score=model_score,
        raise_reasons=raise_reasons,
    )


def screen_from_values(
    *,
    age: int | None,
    male: bool | None,
    height_cm: float | None,
    weight_kg: float | None,
    neck_cm: float | None,
    snoring: bool | None,
    tired: bool | None,
    observed_apnea: bool | None,
    hypertension: bool | None,
    conditions: Sequence[str] = (),
    values: Mapping[str, float | None],
    z_scores: Mapping[str, float | None],
    nights_available: int,
    nights_with_spo2: int,
    artifact: Mapping | None,
    synthetic: bool = False,
    config: Mapping | None = None,
) -> ApneaDecision:
    """One call from plain values to a decision; the schema wrapper only has to unpack its models."""
    bmi = bmi_from(height_cm, weight_kg)
    in_conditions = any(str(c).strip().lower() == "hypertension" for c in conditions)
    hypertension_from_conditions = in_conditions and hypertension is not True
    if in_conditions:
        hypertension = True
    sb = score_stopbang(
        snoring=snoring,
        tired=tired,
        observed_apnea=observed_apnea,
        hypertension=hypertension,
        bmi=bmi,
        age=age,
        neck_cm=neck_cm,
        male=male,
    )
    return decide_apnea_tier(
        sb,
        bmi=bmi,
        artifact=artifact,
        resting_hr_bpm=values.get("resting_heart_rate_bpm"),
        hrv_rmssd_ms=values.get("hrv_rmssd_ms"),
        z_scores=z_scores,
        nights_available=nights_available,
        nights_with_spo2=nights_with_spo2,
        synthetic=synthetic,
        hypertension_from_conditions=hypertension_from_conditions,
        config=config,
    )
